/**
 * Static, deterministic KPI explanations for the Executive Dashboard's
 * info popovers (DESIGN_SPECIFICATION.md §7.1). Every field here is fixed
 * copy — never AI-generated, never data-dependent — matching
 * OPERATIONS_ENGINE_SPEC.md's formulas and thresholds exactly, so this
 * file is the single source of truth to update if a formula ever changes.
 * "Current interpretation" (the one genuinely data-dependent field the
 * spec calls for) is deliberately NOT here — it's computed at render time
 * from the live value, see kpiInterpretation() below.
 */
export interface KpiInfoContent {
  definition: string;
  whyItMatters: string;
  howCalculated: string;
  idealRange: string;
  howToImprove: string[];
  /**
   * Optional — the concrete operational consequence of leaving this metric
   * unaddressed (Phase 5, Inventory Intelligence). Omitted by the original
   * six Dashboard KPI definitions below (their popovers render unchanged
   * without it — see KpiInfoPopover); every new Inventory KPI definition
   * includes it, since "what happens if I ignore it" is one of the five
   * questions the Inventory page is required to answer.
   */
  whatIfIgnored?: string;
}

