export type KpiDefinitionKey = keyof typeof KPI_DEFINITIONS;

/**
 * The one genuinely data-dependent sentence in a KPI info panel — computed
 * from the live value, not stored as static copy. Still fully
 * deterministic (a template filled with a real number), never AI-generated.
 */
export function kpiCurrentInterpretation(key: KpiDefinitionKey, value: number | null): string {
  if (value === null) return "Not enough data yet to compute this metric.";

  switch (key) {
    case "operationsHealthScore":
      return value >= 80
        ? `Currently ${Math.round(value)}/100 — operations are in good shape.`
        : value >= 60
          ? `Currently ${Math.round(value)}/100 — needs attention in at least one area.`
          : `Currently ${Math.round(value)}/100 — requires immediate attention.`;
    case "inventoryTurnover":
      return value >= 8
        ? `Currently ${value.toFixed(1)}x/year — at or above the 8x target.`
        : `Currently ${value.toFixed(1)}x/year — below the 8x target, worth reviewing alongside stockout risk.`;
    case "supplierReliability":
      return value >= 70
        ? `Currently averaging ${Math.round(value)}/100 — above the reliability threshold.`
        : `Currently averaging ${Math.round(value)}/100 — below the 70-point reliability threshold.`;
    case "activeRecommendations":
      return `${Math.round(value)} recommendation${value === 1 ? "" : "s"} currently open.`;
    case "forecastAccuracy":
      return value >= 80
        ? `Currently ${value.toFixed(1)}% — forecasts are trustworthy.`
        : `Currently ${value.toFixed(1)}% — below the 80% trust threshold.`;
    case "overduePurchaseOrders":
      return value === 0
        ? "No purchase orders are currently overdue."
        : `${Math.round(value)} purchase order${value === 1 ? " is" : "s are"} currently overdue.`;
    case "totalPositions":
      return `${Math.round(value)} inventory position${value === 1 ? "" : "s"} in the current view.`;
    case "criticalInventoryPositions":
      return value === 0
        ? "No positions are currently critical."
        : `${Math.round(value)} position${value === 1 ? " is" : "s are"} critically low right now.`;
    case "overstockedInventoryPositions":
      return value === 0
        ? "No positions are currently overstocked."
        : `${Math.round(value)} position${value === 1 ? " is" : "s are"} overstocked right now.`;
    case "totalInventoryValue":
      return `Currently ₹${Math.round(value).toLocaleString("en-IN")} in on-hand inventory value.`;
    case "movingAverageAccuracy":
    case "exponentialSmoothingAccuracy":
      return value >= 80
        ? `Currently ${value.toFixed(1)}% for this product — trustworthy.`
        : `Currently ${value.toFixed(1)}% for this product — below the 80% trust threshold.`;
    case "abcClassification":
      return `${Math.round(value)} product(s) currently in Class A — the highest-priority segment.`;
    default:
      return "";
  }
}
